/**
 * The term's arithmetic, tested at the boundaries the pre-registration names.
 *
 * `preregistration-298.md` fixes four statements that this file has to be able to fail: the asymmetry is bounded
 * and dimensionless; a pair moves by at most λ; an unfitted edge pays nothing and is distinguishable from an edge
 * measured to be independent; and the bound is what keeps the three losses out of reach. The last one is not a
 * test of this module — it is arithmetic over an artifact — but the first three are, and they are tested here
 * with numbers small enough to check by hand rather than with fixtures generated by the code under test.
 */

import { describe, expect, it } from 'vitest';

import { countObservations, edgeKeyOf, type EdgeCounts } from '../src/containment-residual.js';
import type { ContainmentCaseRow } from '../src/containment-rows.js';
import {
  asymmetryOf,
  fusionPairs,
  gradeByTerm,
  phiByEdge,
  termTransfers,
  type TermTransfer,
} from '../src/containment-term.js';

/** A pair row as the dump carries it: the caller above, the callee below, both measured unless stated. */
function pair(
  upper: string,
  lower: string,
  upperExcursion: number | undefined,
  lowerExcursion: number | undefined,
  decision: 'not-larger' | 'no-failed-interface' | 'inverted' = 'not-larger',
) {
  return {
    upper,
    lower,
    decision,
    ...(upperExcursion === undefined ? {} : { upperExcursion }),
    ...(lowerExcursion === undefined ? {} : { lowerExcursion }),
  };
}

/** A φ map from `[a, b, value]` triples, keyed unordered the way the residual module keys it. */
function phiMap(entries: readonly (readonly [string, string, number])[]): Map<string, number> {
  return new Map(entries.map(([a, b, value]) => [edgeKeyOf(a, b), value]));
}

describe('the asymmetry of a pair', () => {
  it('is 1 when the caller is exactly in its band', () => {
    // (v − u)/(v + u) with u = 0: the callee's whole excursion is the asymmetry. This is the case the sweep
    // treats as the cleanest propagation signature, so it must be the maximum of the scale rather than NaN.
    expect(asymmetryOf(0, 0.75)).toBe(1);
    expect(asymmetryOf(0, 4.35)).toBe(1);
  });

  it('is the normalised excess when both sides moved', () => {
    expect(asymmetryOf(0.5, 1.5)).toBeCloseTo(0.5, 15);
    expect(asymmetryOf(1, 3)).toBeCloseTo(0.5, 15);
    expect(asymmetryOf(3, 1)).toBeCloseTo(-0.5, 15);
  });

  it('is 0 when the two excursions are equal', () => {
    // Not a refusal — the predicate is somebody else's question. A pair that moved equally carries no
    // directional evidence, and the scale says so rather than the function returning a sentinel.
    expect(asymmetryOf(1.25, 1.25)).toBe(0);
  });

  it('is undefined when neither side can carry a denominator', () => {
    // Both in band: (0 − 0)/(0 + 0). The pair cannot qualify anyway, but a NaN here would propagate into a
    // bonus and turn a no-op into a sorting accident, so it is spelled as absence.
    expect(asymmetryOf(0, 0)).toBeNull();
  });

  it('is undefined when a side was not measured', () => {
    expect(asymmetryOf(undefined, 1)).toBeNull();
    expect(asymmetryOf(1, undefined)).toBeNull();
    expect(asymmetryOf(undefined, undefined)).toBeNull();
  });
});

describe('the transfers the term pays', () => {
  it('pays lambda × phi × asymmetry to the callee and nothing to the caller', () => {
    const transfers = termTransfers({
      pairs: [pair('caller', 'callee', 0, 0.5)],
      phi: phiMap([['caller', 'callee', 0.4]]),
      lambda: 1,
      margin: 0,
    });
    expect(transfers).toHaveLength(1);
    expect(transfers[0]!.caller).toBe('caller');
    expect(transfers[0]!.callee).toBe('callee');
    expect(transfers[0]!.asymmetry).toBe(1);
    expect(transfers[0]!.delta).toBeCloseTo(0.4, 15);
  });

  it('scales by lambda, so the sweep is the same arithmetic at a different magnitude', () => {
    const at = (lambda: number): number =>
      termTransfers({
        pairs: [pair('caller', 'callee', 1, 3)],
        phi: phiMap([['caller', 'callee', 0.5]]),
        lambda,
        margin: 0,
      })[0]!.delta;
    expect(at(1)).toBeCloseTo(0.25, 15); // 0.5 × 0.5 asymmetry
    expect(at(4)).toBeCloseTo(1, 15);
    expect(at(0)).toBe(0);
  });

  it('cannot pay a pair more than lambda, which is the bound the pre-registration rests on', () => {
    // |phi| ≤ 1 and asymmetry ≤ 1 by construction, so the maximum over every possible pair is λ. This is the
    // sentence "no loss is possible below the smallest of the three gaps" reduces to, and if it ever fails the
    // pre-registration's algebra is wrong rather than merely unlucky.
    const most = termTransfers({
      pairs: [pair('caller', 'callee', 0, 1e-9)],
      phi: phiMap([['caller', 'callee', 1]]),
      lambda: 1,
      margin: 0,
    })[0]!.delta;
    expect(most).toBeCloseTo(1, 12);
    expect(most).toBeLessThanOrEqual(1 + 1e-12);
  });

  it('refuses a pair the callee did not outrun', () => {
    expect(
      termTransfers({
        pairs: [pair('caller', 'callee', 1, 1)],
        phi: phiMap([['caller', 'callee', 0.9]]),
        lambda: 1,
        margin: 0,
      }),
    ).toEqual([]);
  });

  it('refuses a pair inside the margin, strictly', () => {
    const pairs = [pair('caller', 'callee', 0, 0.5)];
    const phi = phiMap([['caller', 'callee', 0.9]]);
    expect(termTransfers({ pairs, phi, lambda: 1, margin: 0.5 })).toEqual([]);
    expect(termTransfers({ pairs, phi, lambda: 1, margin: 0.4 })).toHaveLength(1);
  });

  it('refuses a pair the profile could not measure', () => {
    expect(
      termTransfers({
        pairs: [pair('caller', 'callee', undefined, 0.5)],
        phi: phiMap([['caller', 'callee', 0.9]]),
        lambda: 1,
        margin: 0,
      }),
    ).toEqual([]);
  });

  it('pays nothing on an edge nobody fitted — and that is a different statement from phi = 0', () => {
    // The distinction the gate keeps as `prior-absent` vs `prior-below`. A term cannot make it in the score,
    // because both contribute exactly 0, so the module returns no transfer at all for the unfitted edge: the
    // census can then count it, and the score is not told a story about an edge nobody measured.
    const pairs = [pair('caller', 'callee', 0, 1)];
    const unfitted = termTransfers({ pairs, phi: new Map(), lambda: 1, margin: 0 });
    const fittedZero = termTransfers({
      pairs,
      phi: phiMap([['caller', 'callee', 0]]),
      lambda: 1,
      margin: 0,
    });
    expect(unfitted).toEqual([]);
    expect(fittedZero).toHaveLength(1);
    expect(fittedZero[0]!.delta).toBe(0);
  });

  it('pays zero on an anti-correlated edge, rather than demoting the callee', () => {
    // φ < 0 means the two ends move AGAINST each other, which is evidence that the pair is not propagating at
    // all. Spending it as a demotion would be a second mechanism — a signed push rather than a bounded licence —
    // and the pre-registration fixes this arm as single-sided. So the transfer is REPORTED with δ = 0: the edge
    // is fitted and it paid nothing, which a census can count, and the case keeps the fusion's order.
    const transfers = termTransfers({
      pairs: [pair('caller', 'callee', 0, 1)],
      phi: phiMap([['caller', 'callee', -0.6]]),
      lambda: 1,
      margin: 0,
    });
    expect(transfers).toHaveLength(1);
    expect(transfers[0]!.phi).toBeCloseTo(-0.6, 12);
    expect(transfers[0]!.delta).toBe(0);
  });

  it('reads the edge in either direction, because phi is symmetric', () => {
    // The sweep always asks about the caller above its callee, and the residual is keyed unordered because the
    // joint and both marginals are. A lookup that honoured one orientation only would silently halve the arm.
    const forward = termTransfers({
      pairs: [pair('a', 'b', 0, 1)],
      phi: phiMap([['a', 'b', 0.5]]),
      lambda: 1,
      margin: 0,
    });
    const reverse = termTransfers({
      pairs: [pair('a', 'b', 0, 1)],
      phi: phiMap([['b', 'a', 0.5]]),
      lambda: 1,
      margin: 0,
    });
    expect(forward).toEqual(reverse);
  });
});

describe('the graded order', () => {
  it('leaves the order untouched when nothing qualified', () => {
    const order = ['x', 'y', 'z'];
    expect(
      gradeByTerm({
        order,
        scores: new Map([
          ['x', 3],
          ['y', 2],
          ['z', 1],
        ]),
        transfers: [],
      }),
    ).toEqual(order);
  });

  it('promotes a callee that the bonus lets past the caller', () => {
    const order = ['caller', 'callee'];
    const graded = gradeByTerm({
      order,
      scores: new Map([
        ['caller', 1.9],
        ['callee', 0.7],
      ]),
      transfers: [{ caller: 'caller', callee: 'callee', phi: 0.9, asymmetry: 1, delta: 1 }],
    });
    // 0.7 + 1 = 1.7 < 1.9 — the bonus is real and still short, which is the whole point of a bounded term.
    expect(graded).toEqual(['caller', 'callee']);
  });

  it('flips the head when the bonus clears the gap, and by no more than the gap requires', () => {
    const order = ['caller', 'callee', 'third'];
    expect(
      gradeByTerm({
        order,
        scores: new Map([
          ['caller', 1.9],
          ['callee', 1.5],
          ['third', 1.4],
        ]),
        transfers: [{ caller: 'caller', callee: 'callee', phi: 0.9, asymmetry: 1, delta: 0.5 }],
      }),
    ).toEqual(['callee', 'caller', 'third']);
  });

  it('keeps the fusion order between candidates whose adjusted scores tie', () => {
    // A tie is not a decision, and a sort that broke it on the service name would let the alphabet rank a case.
    // The tie-break is the fusion's own order, which is the thing being refined.
    const order = ['alpha', 'beta'];
    expect(
      gradeByTerm({
        order,
        scores: new Map([
          ['alpha', 2],
          ['beta', 1],
        ]),
        transfers: [{ caller: 'alpha', callee: 'beta', phi: 1, asymmetry: 1, delta: 1 }],
      }),
    ).toEqual(['alpha', 'beta']);
  });

  it('sums two transfers that name the same callee', () => {
    // Adjacency guarantees this cannot happen on a real case — a candidate has at most one pair above it — so
    // the behaviour is defined for the day the term is evaluated on something wider than the chain, and defined
    // as addition rather than as "last one wins".
    const transfers: TermTransfer[] = [
      { caller: 'a', callee: 'c', phi: 0.5, asymmetry: 1, delta: 0.4 },
      { caller: 'b', callee: 'c', phi: 0.5, asymmetry: 1, delta: 0.3 },
    ];
    expect(
      gradeByTerm({
        order: ['a', 'b', 'c'],
        scores: new Map([
          ['a', 2],
          ['b', 1.9],
          ['c', 1.3],
        ]),
        transfers,
      }),
    ).toEqual(['a', 'c', 'b']);
  });

  it('refuses to order a case whose candidate has no score', () => {
    // A candidate the engine could not score has no place in a sort by score, and putting it anywhere would be
    // inventing one. `null` is the refusal, and the caller counts it rather than reading it as a no-op.
    expect(
      gradeByTerm({
        order: ['caller', 'callee'],
        scores: new Map([['caller', 1]]),
        transfers: [{ caller: 'caller', callee: 'callee', phi: 1, asymmetry: 1, delta: 1 }],
      }),
    ).toBeNull();
  });

  it('refuses a score that is not finite, on the same principle', () => {
    expect(
      gradeByTerm({
        order: ['caller', 'callee'],
        scores: new Map([
          ['caller', 1],
          ['callee', Number.POSITIVE_INFINITY],
        ]),
        transfers: [],
      }),
    ).toBeNull();
  });
});

describe('phi by edge', () => {
  it('reports phi for every edge over the population floor and no value for the rest', () => {
    const counts = new Map<string, EdgeCounts>([
      // 20 observations, both ends out together in 20 of them: p = q = 1, so ρ = 0 and φ = 1 / 0 → the
      // degenerate case, which the residual module reports as 0 variance rather than as a number.
      [edgeKeyOf('always', 'always2'), { measured: 20, bothOut: 20, aOut: 20, bOut: 20 }],
      // 20 observations, 10 and 10, joint 8: p = q = 0.5, ρ = 0.15, φ = 0.15 / 0.25 = 0.6.
      [edgeKeyOf('half', 'half2'), { measured: 20, bothOut: 8, aOut: 10, bOut: 10 }],
      // Below the floor: no estimate at all, which is different from an estimate of zero.
      [edgeKeyOf('thin', 'thin2'), { measured: 4, bothOut: 4, aOut: 4, bOut: 4 }],
    ]);
    const phi = phiByEdge(counts);
    expect(phi.get(edgeKeyOf('half', 'half2'))).toBeCloseTo(0.6, 12);
    expect(phi.has(edgeKeyOf('thin', 'thin2'))).toBe(false);
    expect(phi.has(edgeKeyOf('always', 'always2'))).toBe(false);
  });

  it('is symmetric in the key, so a caller/callee lookup cannot miss', () => {
    const phi = phiByEdge(
      new Map([[edgeKeyOf('caller', 'callee'), { measured: 10, bothOut: 5, aOut: 5, bOut: 5 }]]),
    );
    expect(phi.get(edgeKeyOf('callee', 'caller'))).toBeCloseTo(1, 12);
  });
});

describe('the fusion order’s own adjacencies', () => {
  /** A case row carrying only what the term reads. */
  function chainRow(
    order: readonly string[],
    edges: readonly (readonly [string, string])[],
    excursions: Readonly<Record<string, number>>,
  ): ContainmentCaseRow {
    return {
      datapack: 'case',
      faultType: 'PodKill',
      sigma: 3,
      margin: 0,
      fusionTop1: order[0] ?? null,
      gatedTop1: order[0] ?? null,
      ungatedTop1: order[0] ?? null,
      shippedTop1: order[0] ?? null,
      replay: 'identical',
      pairs: [],
      ungatedPairs: [],
      chain: {
        order: [...order],
        edges: edges.map(([from, to]) => [from, to] as const),
        excursions,
        failedInterfaces: {},
        flows: {},
        failingEdges: {},
        attribution: 'count',
      },
    } as unknown as ContainmentCaseRow;
  }

  it('reads adjacency from the fusion order, not from a sweep', () => {
    // The distinction is the module's whole claim: a term cannot depend on a walk, so the pair set is a function
    // of the case. `a→b` is adjacent and joined, `b→c` is adjacent and NOT joined (no edge), `a→c` is joined and
    // not adjacent.
    const pairs = fusionPairs(
      chainRow(
        ['a', 'b', 'c'],
        [
          ['a', 'b'],
          ['a', 'c'],
        ],
        { a: 0, b: 0.5, c: 0 },
      ),
    );
    expect(pairs).toEqual([{ upper: 'a', lower: 'b', upperExcursion: 0, lowerExcursion: 0.5 }]);
  });

  it('omits a side the profile could not measure rather than zeroing it', () => {
    const pairs = fusionPairs(chainRow(['a', 'b'], [['a', 'b']], { a: 0 }));
    expect(pairs).toEqual([{ upper: 'a', lower: 'b', upperExcursion: 0 }]);
    expect('lowerExcursion' in pairs[0]!).toBe(false);
  });

  it('is empty for a row written before the chain existed', () => {
    expect(fusionPairs({ ...chainRow(['a', 'b'], [], {}), chain: undefined } as never)).toEqual([]);
  });
});

describe('counting a population of pairs', () => {
  it('counts the same observation the same way whatever grouping it arrives in', () => {
    // The refactor that let the term fit on its own population without a second implementation of counting. If
    // these two calls ever disagree, one of the two arms is being measured by different arithmetic.
    const groups: [string, string, number, number][][] = [
      [
        ['a', 'b', 3, 0],
        ['a', 'b', 0, 2],
      ],
      [['a', 'b', 1, 1]],
    ];
    const counted = countObservations(
      groups.map((group) =>
        group.map(([upper, lower, upperExcursion, lowerExcursion]) => ({
          upper,
          lower,
          upperExcursion,
          lowerExcursion,
        })),
      ),
    );
    expect(counted.get(edgeKeyOf('a', 'b'))).toEqual({ measured: 3, bothOut: 1, aOut: 2, bOut: 2 });
  });

  it('skips a pair with an unmeasured side instead of counting it as in band', () => {
    const counted = countObservations([[{ upper: 'a', lower: 'b', upperExcursion: 2 }]]);
    expect(counted.size).toBe(0);
  });
});

describe('the remaining boundary of the pair reader', () => {
  it('omits an unmeasured CALLER side too, not only an unmeasured callee', () => {
    // The two spreads are separate expressions and a fixture that only starves the lower side would leave the
    // upper one's absence branch untested — which is the branch that runs on every case whose rank-1 candidate
    // the profile could not measure.
    const row = {
      datapack: 'case',
      chain: {
        order: ['a', 'b'],
        edges: [['a', 'b']],
        excursions: { b: 1.5 },
        failedInterfaces: {},
        flows: {},
        failingEdges: {},
        attribution: 'count',
      },
    } as unknown as ContainmentCaseRow;
    const pairs = fusionPairs(row);
    expect(pairs).toEqual([{ upper: 'a', lower: 'b', lowerExcursion: 1.5 }]);
    expect('upperExcursion' in pairs[0]!).toBe(false);
    // And the term pays nothing on it: an unmeasured side is not a zero excursion.
    expect(termTransfers({ pairs, phi: phiMap([['a', 'b', 0.9]]), lambda: 1, margin: 0 })).toEqual(
      [],
    );
  });
});
